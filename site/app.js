const toggle = document.getElementById("lang-toggle");
const root = document.documentElement;

function apply(lang) {
  const dict = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) el.innerHTML = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });
  root.lang = lang === "zh" ? "zh-Hant" : "en";
  toggle.textContent = lang === "zh" ? "EN" : "中文";
  localStorage.setItem("wa-lang", lang);
}

const saved = localStorage.getItem("wa-lang");
const initial = saved || (navigator.language && navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en");
apply(initial);

toggle.addEventListener("click", () => {
  apply(root.lang.startsWith("zh") ? "en" : "zh");
});
